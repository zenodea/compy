#!/usr/bin/env python3
"""Generates program icon drawables from a pinned Simple Icons release.

Run it only when changing the icon list. The output is committed, so builds don't need it.
"""
import io
import json
import re
import tarfile
import urllib.request
from pathlib import Path

VERSION = "16.36.0"
URL = f"https://registry.npmjs.org/simple-icons/-/simple-icons-{VERSION}.tgz"
SLUGS = """
claude anthropic googlegemini githubcopilot cursor git github gitlab docker python nodedotjs npm
pnpm yarn bun deno rust go zig ruby php swift kotlin openjdk cplusplus lua elixir haskell dotnet
vim neovim gnuemacs helix tmux gnubash zsh fishshell nushell postgresql sqlite redis mysql
kubernetes terraform ansible nixos homebrew tailscale vercel cloudflare ollama mistralai
huggingface jupyter xcode
""".split()
ALLOWED_LICENSES = {None, "CC0-1.0", "CC-BY-3.0", "CC-BY-4.0", "MIT", "Apache-2.0", "BSD-3-Clause"}

root = Path(__file__).resolve().parent.parent
drawables = root / "app/src/main/res/drawable"
table = root / "app/src/main/java/dev/compy/ui/ProgramIconTable.kt"
attribution = root / "app/src/main/assets/icons/ATTRIBUTION.md"


def normalize(path):
    """Writes arc flags out in full, because Android's parser can't read SVG's compact form."""
    out = []
    for command, args in re.findall(r"([a-zA-Z])([^a-zA-Z]*)", path):
        if command not in "aA":
            out.append(command + args.strip())
            continue
        i = 0
        values = []
        position = 0
        number = re.compile(r"\s*,?\s*([-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?)")
        flag = re.compile(r"\s*,?\s*([01])")
        while True:
            pattern = flag if i % 7 in (3, 4) else number
            match = pattern.match(args, position)
            if not match:
                break
            values.append(match.group(1))
            position = match.end()
            i += 1
        out.append(command + " ".join(values))
    return "".join(out)


with urllib.request.urlopen(URL) as response:
    archive = tarfile.open(fileobj=io.BytesIO(response.read()), mode="r:gz")

data = json.load(archive.extractfile("package/data/simple-icons.json"))
data = data if isinstance(data, list) else data["icons"]
by_slug = {entry.get("slug"): entry for entry in data}

entries = []
credits = []
for slug in SLUGS:
    entry = by_slug[slug]
    license_type = (entry.get("license") or {}).get("type")
    if license_type not in ALLOWED_LICENSES:
        print(f"skipping {slug}: {license_type}")
        continue
    svg = archive.extractfile(f"package/icons/{slug}.svg").read().decode()
    path = normalize(re.search(r' d="([^"]+)"', svg).group(1))
    fill_type = ' android:fillType="evenOdd"' if 'fill-rule="evenodd"' in svg else ""
    (drawables / f"prog_{slug}.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n'
        f'    <path android:fillColor="#FFFFFFFF"{fill_type} android:pathData="{path}" />\n'
        "</vector>\n"
    )
    entries.append(f'    "{slug}" to ProgramGlyph(R.drawable.prog_{slug}, 0xFF{entry["hex"]}.toInt()),')
    credits.append(f"- {entry['title']}: {license_type or 'CC0-1.0'} ({entry.get('source', '')})")

table.write_text(
    "package dev.compy.ui\n\n"
    "import dev.compy.R\n\n"
    "// Generated by scripts/generate-program-icons.py. Don't edit by hand.\n\n"
    "data class ProgramGlyph(val drawable: Int, val brandColor: Int)\n\n"
    "val SimpleIconGlyphs: Map<String, ProgramGlyph> = mapOf(\n" + "\n".join(entries) + "\n)\n"
)
attribution.parent.mkdir(parents=True, exist_ok=True)
attribution.write_text(
    f"# Program icons\n\nFrom Simple Icons {VERSION} (https://simpleicons.org), under CC0-1.0 unless noted.\n"
    "All names and logos are trademarks of their owners and don't imply endorsement of Compy.\n\n"
    + "\n".join(credits) + "\n"
)
print(f"wrote {len(entries)} icons")
